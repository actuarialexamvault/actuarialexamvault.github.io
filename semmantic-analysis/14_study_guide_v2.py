def _extract_question(text: str) -> str:
    sol_idx = text.find("SOLUTION")
    if sol_idx > 0:
        return text[:sol_idx].replace("QUESTION:", "").strip()
    return text.replace("QUESTION:", "").strip()


def _extract_solution(text: str) -> str:
    for marker in ("SOLUTION:", "SOLUTION\n"):
        idx = text.find(marker)
        if idx != -1:
            return text[idx + len(marker):].strip()
    return ""


COMMAND_WORD_RE = re.compile(
    r"\b(calculate|derive|define|describe|explain|discuss|outline|list|state|"
    r"comment|assess|compare|suggest|recommend|justify|show|determine|estimate)\b",
    re.IGNORECASE,
)

def _command_words(text: str) -> list[str]:
    return sorted(set(m.group(0).lower() for m in COMMAND_WORD_RE.finditer(text)))


def _priority_badge(n_q: int, rec: float) -> str:
    if n_q >= 30 or rec >= 12:
        level, colour = "HIGH", "#c0392b"
    elif n_q >= 20 or rec >= 8:
        level, colour = "MEDIUM", "#d35400"
    else:
        level, colour = "LOW", "#27ae60"
    return f'<span style="background:{colour};color:#fff;font-size:10px;font-weight:700;padding:2px 9px;border-radius:10px;margin-left:8px;vertical-align:middle">{level}</span>'



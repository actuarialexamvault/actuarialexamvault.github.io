def _q_card_html(a: dict, q: dict) -> str:
    yr = q.get("year", "")
    sess = q.get("session", "")
    qnum = a["question_id"].split("_")[-1]
    marks_str = f"  [{int(float(a['marks']))} min]" if a.get("marks") and float(a["marks"]) > 0 else ""

    q_text = _extract_question(q.get("text", ""))
    sol_text = _extract_solution(q.get("text", ""))
    cmd_tags = " ".join(f'<span class="cmd-tag">{c}</span>' for c in _command_words(q_text))

    method = a.get("method", "")
    method_label = {
        "tagged": "",
        "inferred": "inferred",
        "cluster_propagated": "cluster",
        "inferred_low_conf": "low-conf",
    }.get(method, method)
    method_tag = f'<span class="method-tag">{method_label}</span>' if method_label else ""

    conflict_tag = ""
    if a.get("cluster_conflict"):
        conflict_tag = '<span class="conflict-tag">&#9888; multi-topic</span>'

    sol_block = ""
    if sol_text.strip():
        sol_html = sol_text.replace("<", "&lt;").replace(">", "&gt;")
        sol_block = (
            f'<span class="sol-toggle" onclick="toggleSol(this)">Show examiner solution ▼</span>'
            f'<div class="sol-body">{sol_html}</div>'
        )
    else:
        sol_block = '<p style="font-size:11px;color:#aaa;margin-bottom:10px">No examiner solution available.</p>'

    q_html = q_text.replace("<", "&lt;").replace(">", "&gt;")

    return f"""
    <div class="q-card">
      <div class="q-header">
        <span>{yr} {sess} &mdash; {qnum}{marks_str}</span>
        {cmd_tags}
        {method_tag}
        {conflict_tag}
      </div>
      <div class="q-body">
        <div class="q-text">{q_html}</div>
        {sol_block}
      </div>
    </div>"""


def _topic_html(folder: str, rank_data: dict, summary_data: dict,
                assignments: list, q_by_id: dict,
                extra_folders: list | None = None) -> str:
    extra_folders = extra_folders or []
    n_q = int(rank_data.get("n_questions", 0))
    rec = float(rank_data.get("recency_score", 0))
    last = rank_data.get("last_tested_year", "")
    rank = rank_data.get("priority_rank", "")
    badge = _priority_badge(n_q, rec)
    section_id = re.sub(r"[^a-zA-Z0-9_-]", "_", folder)

    # -- Summary block --
    if summary_data:
        summary_html = f'<div class="summary">{summary_data["summary_html"]}</div>'
    else:
        summary_html = (
            '<div class="no-summary">'
            'No AI summary yet &mdash; run <code>13_llm_summaries.py</code> to generate one.'
            '</div>'
        )

    # -- Past exam questions --
    all_folders = [folder] + extra_folders
    topic_assignments = [
        a for a in assignments
        if a["folder"] in all_folders and a["confidence"] in ("high", "medium")
    ]
    # Sort: most recent first
    topic_assignments.sort(key=lambda a: (-(int(a["year"]) if a["year"] else 0), a["session"]))
    if MAX_QUESTIONS_PER_TOPIC:
        topic_assignments = topic_assignments[:MAX_QUESTIONS_PER_TOPIC]

    # Deduplicate (a question can appear once per folder in assignments)
    seen_qids = set()
    unique_assignments = []
    for a in topic_assignments:
        if a["question_id"] not in seen_qids:
            seen_qids.add(a["question_id"])
            unique_assignments.append(a)

    q_cards = ""
    for a in unique_assignments:
        q = q_by_id.get(a["question_id"])
        if q:
            q_cards += _q_card_html(a, q)

    n_shown = len(unique_assignments)
    questions_section = f"""
  <div class="questions-toggle" onclick="toggleQuestions(this)">
    <h3>Past Exam Questions ({n_shown})</h3>
    <span class="qarrow" style="color:#aaa;font-size:16px">&#9662;</span>
  </div>
  <div class="questions-body">
    {q_cards}
  </div>"""

    display_name = re.sub(r'^\d+\.\s*', '', folder)
    return f"""
<div class="topic" id="{section_id}">
  <div class="topic-header">
    <h2>#{rank} &nbsp; {display_name}{badge}</h2>
    <div class="topic-meta">
      {n_q} exam questions &nbsp;|&nbsp; last tested {last} &nbsp;|&nbsp;
      recency score {rec:.2f}
    </div>
  </div>
  {summary_html}
  {questions_section}
</div>"""


def _sidebar_item(folder: str, rank_data: dict) -> str:
    rank = rank_data.get("priority_rank", "?")
    n_q = rank_data.get("n_questions", 0)
    short = re.sub(r"^\d+\.\s*", "", folder)
    section_id = re.sub(r"[^a-zA-Z0-9_-]", "_", folder)
    return (
        f'<a href="#{section_id}">{short}'
        f'<span class="badge">#{rank} &middot; {n_q}q</span></a>'
    )


